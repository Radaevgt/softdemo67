def help_text() -> str:
    """Инструкция.

    Перечень вопросов собирается из самого опроса, а не переписывается рядом:
    иначе инструкция разойдётся с вопросами при первой же правке признаков.
    """
    questions = "\n".join(
        # Подсказка написана с прописной как самостоятельная фраза, а здесь она
        # продолжает предложение после двоеточия.
        f"— {attribute.label}: {attribute.source_hint[0].lower()}{attribute.source_hint[1:]}."
        for attribute in ATTRIBUTES
    )
    return HELP_INTRO + questions + HELP_OUTRO


